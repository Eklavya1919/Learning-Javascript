// string to number

let age = "33"
let numage = Number(age)

console.log(numage);
console.log(typeof numage);


// number to string

let strage = String(numage)
console.log(strage);
console.log(typeof strage);

// "33" -> 33
// "33abc" -> NaN
// 1 -> true, 0-> false
// "eklavya" -> true, "" -> false // Empty string is false and non empty string is true
// If value can't be converted then it is just stored as NaN









